#!/usr/bin/env python3
"""Generate the API reference pages from the public API manifest.

The reference is generated for two reasons:

* **Completeness.** Every name in ``docs/api-manifest.json`` lands on exactly
  one page, so a public name cannot be missing from the reference.
* **Reviewability.** The generated Markdown is committed. Rendered signatures
  and docstrings come from ``mkdocstrings`` at build time, so prose, signatures,
  and parameter contracts cannot drift apart. ``--check`` fails when the
  committed pages are stale.

The curated input is ``docs/reference/_registry.toml``: page identity, stability
tier, cross-links, grouping titles, and the quick-path table. Everything else is
derived from ``torchsky``. Run from the repository root:

    pixi run docs-reference           # regenerate
    pixi run docs-reference-check     # verify committed pages are current
"""

from __future__ import annotations

import argparse
import importlib
import inspect
import json
import re
import sys
import tomllib
from pathlib import Path

import griffe

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src"
DOCS = ROOT / "docs"
REFERENCE = DOCS / "reference"
MANIFEST = DOCS / "api-manifest.json"
REGISTRY = REFERENCE / "_registry.toml"
CONFIG = ROOT / "zensical.toml"

HEADER = "<!-- Generated by scripts/gen_reference.py; edit _registry.toml instead. -->"
HANDWRITTEN = {"runtime-contract.md"}
MKDO_OPTIONS = (
    "      heading_level: 3\n"
    "      show_root_heading: false\n"
    "      show_root_toc_entry: false\n"
    "      filters: []\n"
)
TIER_TEXT = {
    "core": (
        "**Stability: core.** Names on this page follow the deprecation policy in "
        "[contributing](../contributing.md)."
    ),
    "compatibility": (
        "**Stability: compatibility.** This page mirrors a familiar upstream API on "
        "top of torchsky kernels. Behavior follows the documented torchsky contract."
    ),
    "experimental": (
        '!!! warning "Experimental surface"\n'
        "    These APIs are under active development. Names, defaults, and result\n"
        "    objects may change between minor releases; pin a version if you depend\n"
        "    on them in production."
    ),
}
RST_ROLE = re.compile(r":(?:class|func|meth|mod|attr|data|obj|exc|py:class|py:func):`~?([^`]+)`")
DOUBLE_BACKTICKS = re.compile(r"``([^`]+)``")


def _load_registry() -> dict:
    return tomllib.loads(REGISTRY.read_text(encoding="utf-8"))


def _load_manifest() -> dict[str, list[str]]:
    return json.loads(MANIFEST.read_text(encoding="utf-8"))


def _clean_docstring(text: str | None) -> str:
    """Turn a module docstring into page prose (first paragraph only)."""
    if not text:
        return ""
    text = inspect.cleandoc(text)
    paragraph: list[str] = []
    for line in text.splitlines():
        if not line.strip():
            if paragraph:
                break
            continue
        paragraph.append(line)
    prose = " ".join(part.strip() for part in paragraph)
    prose = RST_ROLE.sub(lambda match: match.group(1).split(".")[-1], prose)
    prose = DOUBLE_BACKTICKS.sub(lambda match: f"`{match.group(1)}`", prose)
    return prose


def _humanize(module_path: str) -> str:
    tail = module_path.rsplit(".", 1)[-1]
    return tail.replace("_", " ").strip().capitalize()


def _group_for(obj: object, namespace: str) -> str:
    if inspect.ismodule(obj):
        return "Submodules"
    module = getattr(obj, "__module__", "") or ""
    if module in {"", namespace, "builtins"}:
        return "Namespace"
    if module.startswith(namespace + "."):
        return module[len(namespace) + 1 :]
    return module.rsplit(".", 1)[-1]


def _resolve(namespace: str, names: list[str]) -> list[tuple[str, object]]:
    module = importlib.import_module(namespace)
    missing: list[str] = []
    resolved: list[tuple[str, object]] = []
    for name in names:
        try:
            resolved.append((name, getattr(module, name)))
        except AttributeError:
            missing.append(name)
    if missing:
        raise SystemExit(f"{namespace}: public names not importable: {missing}")
    return resolved


def _page_head(
    *,
    namespace: str,
    tier: str,
    intro: str,
    related: list[str],
    body_intro: str,
) -> list[str]:
    lines = [HEADER, "", f"# `{namespace}`", ""]
    if tier in TIER_TEXT:
        lines.extend([TIER_TEXT[tier], ""])
    if intro:
        lines.extend([intro, ""])
    if related:
        links = ", ".join(
            f"[{Path(target).stem.replace('_', ' ')}](../{target})" for target in related
        )
        lines.extend([f"**Guides:** {links}", ""])
    lines.extend(["---", "", body_intro, ""])
    return lines


def _member_directive(namespace: str, members: list[str]) -> list[str]:
    lines = [f"::: {namespace}", "    options:", "      members:"]
    lines.extend(f"        - {member}" for member in members)
    lines.append(MKDO_OPTIONS.rstrip("\n"))
    lines.append("")
    return lines


def _is_typing_alias(obj: object) -> bool:
    return type(obj).__module__ == "typing" or str(obj).startswith("typing.")


def _canonical_path(obj: object) -> str:
    module = getattr(obj, "__module__", "")
    qualname = getattr(obj, "__qualname__", getattr(obj, "__name__", ""))
    return f"{module}.{qualname}"


def _render_members(namespace: str, members: list[str], objects: dict[str, object], griffe_module: object) -> list[str]:
    """Render one group's members without losing dynamically exported names.

    mkdocstrings follows static imports. Names exported through a module
    ``__getattr__`` (or shadowed by a same-named submodule) are invisible to it,
    so they get an explicit public anchor plus a canonical-path directive or a
    compact entry. Either way the public anchor exists for cross-references.
    """
    lines: list[str] = []
    inline: list[str] = []
    for name in members:
        obj = objects[name]
        if _is_typing_alias(obj):
            lines.extend([f'<a id="{namespace}.{name}"></a>', "", f"**`{name}`**", "", "```python", str(obj), "```", ""])
            continue
        static_member = griffe_module.members.get(name)
        unresolved_alias = (
            isinstance(static_member, griffe.Alias) and static_member.resolved is False
        )
        if (
            static_member is not None
            and not unresolved_alias
            and not inspect.ismodule(obj)
            and not isinstance(static_member, griffe.Module)
        ):
            inline.append(name)
            continue
        canonical = _canonical_path(obj)
        canonical_member = griffe_module
        try:
            canonical_member = griffe.load(canonical.rsplit(".", 1)[0], search_paths=[str(SRC)])
        except Exception:
            canonical_member = None
        if canonical_member is not None and canonical.rsplit(".", 1)[-1] in canonical_member.members:
            lines.extend(
                [
                    f'<a id="{namespace}.{name}"></a>',
                    "",
                    f"::: {canonical}",
                    "    options:",
                    "      heading_level: 3",
                    "      show_root_heading: true",
                    "      show_root_toc_entry: true",
                    "      filters: []",
                    "",
                ]
            )
        else:
            lines.extend([f'<a id="{namespace}.{name}"></a>', "", f"### `{name}`", ""])
            try:
                lines.extend(["```python", f"{name}{inspect.signature(obj)}", "```", ""])
            except (TypeError, ValueError):
                pass
            summary = _clean_docstring(inspect.getdoc(obj))
            if summary:
                lines.extend([summary, ""])
    if inline:
        lines.extend(_member_directive(namespace, inline))
    return lines


def _render_root(entry: dict, manifest: dict[str, list[str]], registry: dict) -> str:
    namespaces = {item["name"]: item for item in registry["namespace"]}
    root = importlib.import_module(entry["name"])
    root_names = manifest[entry["name"]]
    classes = [name for name in root_names if not inspect.ismodule(getattr(root, name))]
    modules = [name for name in root_names if inspect.ismodule(getattr(root, name))]
    lines = _page_head(
        namespace=entry["name"],
        tier=entry["tier"],
        intro=entry.get("intro", ""),
        related=entry.get("related", []),
        body_intro=(
            "The package root exposes one class and the public namespaces. Domain\n"
            "namespaces keep imports light: they load on first access."
        ),
    )
    if classes:
        lines.extend(["## Top-level namespace", ""])
        lines.extend(_member_directive(entry["name"], classes))
    if modules:
        lines.extend(["## Public namespaces", "", "| Namespace | Tier | Reference |", "|---|---|---|"])
        for name in modules:
            full = f"{entry['name']}.{name}"
            target = namespaces[full]
            lines.append(f"| `{full}` | {target['tier']} | [reference]({target['slug']}.md) |")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def _render_namespace(entry: dict, manifest: dict[str, list[str]], registry: dict) -> str:
    namespace = entry["name"]
    module = importlib.import_module(namespace)
    resolved = _resolve(namespace, manifest[namespace])
    objects = dict(resolved)
    griffe_module = griffe.load(namespace, search_paths=[str(SRC)])
    groups: dict[str, list[str]] = {}
    for name, obj in resolved:
        groups.setdefault(_group_for(obj, namespace), []).append(name)

    lines = _page_head(
        namespace=namespace,
        tier=entry["tier"],
        intro=entry.get("intro") or _clean_docstring(module.__doc__),
        related=entry.get("related", []),
        body_intro=(
            "This reference is generated from the package source. Names are grouped by\n"
            "the module that defines them; import every name from the public\n"
            f"namespace `{namespace}` unless the group text says otherwise."
        ),
    )
    module_entries = {item["name"]: item for item in registry.get("module", [])}
    ordered = sorted(groups, key=lambda key: (key != "Namespace", key == "Submodules", key))
    for key in ordered:
        members = groups[key]
        if key == "Submodules":
            lines.extend(["## Submodules", "", "| Module | Stability | Reference |", "|---|---|---|"])
            for member in members:
                full = f"{namespace}.{member}"
                target = module_entries.get(full)
                if target is None:
                    raise SystemExit(f"missing [[module]] registry entry for {full}")
                lines.append(f"| `{full}` | {target['tier']} | [reference]({target['slug']}.md) |")
            lines.append("")
            continue
        title = (
            "Top-level namespace"
            if key == "Namespace"
            else registry.get("group_titles", {}).get(key, _humanize(key))
        )
        lines.extend([f"## {title}", ""])
        lines.extend(_render_members(namespace, members, objects, griffe_module))
    return "\n".join(lines).rstrip() + "\n"


def _render_module(entry: dict, registry: dict) -> str:
    namespace = entry["name"]
    if "alias_of" in entry:
        alias_of = entry["alias_of"]
        target = next(item for item in registry["module"] if item["name"] == alias_of)
        lines = _page_head(
            namespace=namespace,
            tier=entry["tier"],
            intro=entry.get("intro", ""),
            related=entry.get("related", []),
            body_intro="",
        )
        lines.extend(
            [
                f'<a id="{namespace}"></a>',
                "",
                f"The names on this page are the documented `{alias_of}` surface.",
                "",
                f"**Full reference:** [`{alias_of}`]({target['slug']}.md)",
                "",
            ]
        )
        return "\n".join(lines).rstrip() + "\n"

    module = importlib.import_module(namespace)
    names = list(getattr(module, "__all__", ()))
    if not names:
        names = sorted(name for name in dir(module) if not name.startswith("_"))
    resolved = _resolve(namespace, names)
    objects = dict(resolved)
    griffe_module = griffe.load(namespace, search_paths=[str(SRC)])
    groups: dict[str, list[str]] = {}
    for name, obj in resolved:
        groups.setdefault(_group_for(obj, namespace), []).append(name)
    lines = _page_head(
        namespace=namespace,
        tier=entry["tier"],
        intro=entry.get("intro") or _clean_docstring(module.__doc__),
        related=entry.get("related", []),
        body_intro=(
            "This page is generated from the module source. Import these names from\n"
            f"`{namespace}`."
        ),
    )
    lines.extend(
        [
            "## Module",
            "",
            f"::: {namespace}",
            "    options:",
            "      heading_level: 3",
            "      show_root_heading: true",
            "      show_root_toc_entry: true",
            "      filters: []",
            "",
        ]
    )
    ordered = sorted(groups, key=lambda key: (key != "Namespace", key))
    for key in ordered:
        if key == "Namespace":
            continue
        members = groups[key]
        lines.extend([f"## {registry.get('group_titles', {}).get(key, _humanize(key))}", ""])
        lines.extend(_render_members(namespace, members, objects, griffe_module))
    return "\n".join(lines).rstrip() + "\n"


def _render_index(registry: dict, manifest: dict[str, list[str]], entries: list[dict]) -> str:
    lines = [
        HEADER,
        "",
        "# API reference",
        "",
        "The reference is generated from the installed package, so signatures, defaults,",
        "and docstrings always match the code. Domain guides explain *why* and *when*;",
        "reference pages carry the contracts.",
        "",
        "## Quick paths",
        "",
        "| Goal | Entry point | Guide |",
        "|---|---|---|",
    ]
    for row in registry.get("quickpaths", {}).get("rows", []):
        entry = row["entry"]
        lines.append(
            f"| {row['goal']} | [`{entry}`]({row['page']}.md#{entry}) | "
            f"[{Path(row['guide']).stem}](../{row['guide']}) |"
        )
    lines.extend(
        [
            "",
            "## Namespaces",
            "",
            "| Namespace | Tier | Names | Reference |",
            "|---|---|---|---|",
        ]
    )
    order = {"core": 0, "compatibility": 1, "experimental": 2}
    for entry in sorted(entries, key=lambda item: (order.get(item["tier"], 3), item["name"])):
        lines.append(
            f"| `{entry['name']}` | {entry['tier']} | {len(manifest[entry['name']])} | "
            f"[reference]({entry['slug']}.md) |"
        )
    modules = registry.get("module", [])
    if modules:
        lines.extend(
            [
                "",
                "## Public modules",
                "",
                "| Module | Tier | Reference |",
                "|---|---|---|",
            ]
        )
        for item in modules:
            lines.append(f"| `{item['name']}` | {item['tier']} | [reference]({item['slug']}.md) |")
    lines.extend(
        [
            "",
            "Every public name in these namespaces is listed exactly once. The",
            "`api-manifest.json` artifact is the frozen name-level contract checked in CI.",
            "",
            "See also: [errors and exceptions](exceptions.md), "
            "[runtime contract](runtime-contract.md), and [architecture](../architecture.md).",
            "",
        ]
    )
    return "\n".join(lines)


def _render_exceptions(manifest: dict[str, list[str]], entries: list[dict]) -> str:
    by_namespace: dict[tuple[str, str], list[tuple[str, str]]] = {}
    for entry in entries:
        namespace = entry["name"]
        module = importlib.import_module(namespace)
        for name in manifest[namespace]:
            obj = getattr(module, name)
            if inspect.isclass(obj) and issubclass(obj, BaseException):
                summary = _clean_docstring(inspect.getdoc(obj)) or "No description."
                by_namespace.setdefault((namespace, entry["slug"]), []).append((name, summary))
    lines = [
        HEADER,
        "",
        "# Errors and exceptions",
        "",
        "Public exception types raised by `torchsky`. Each type is also documented on",
        "its namespace reference page.",
        "",
    ]
    if not by_namespace:
        lines.append("No public exception classes are currently exported.")
    for (namespace, slug), items in sorted(by_namespace.items()):
        lines.extend([f"## `{namespace}`", ""])
        for name, summary in items:
            lines.extend(
                [f"**[`{name}`]({slug}.md#{namespace}.{name})**", "", summary, ""]
            )
    return "\n".join(lines).rstrip() + "\n"


def _nav_pages() -> list[str]:
    config = tomllib.loads(CONFIG.read_text(encoding="utf-8"))

    def walk(node: object) -> list[str]:
        pages: list[str] = []
        if isinstance(node, list):
            for item in node:
                pages.extend(walk(item))
        elif isinstance(node, dict):
            for value in node.values():
                pages.extend(walk(value))
        elif isinstance(node, str) and node.startswith("reference/"):
            pages.append(node)
        return pages

    return walk(config["project"].get("nav", []))


def generate() -> dict[Path, str]:
    registry = _load_registry()
    manifest = _load_manifest()
    entries = registry["namespace"]
    namespaces = [entry["name"] for entry in entries]
    if sorted(namespaces) != sorted(manifest):
        missing = sorted(set(manifest) - set(namespaces))
        extra = sorted(set(namespaces) - set(manifest))
        raise SystemExit(f"registry/manifest mismatch; missing={missing} extra={extra}")
    slugs = [entry["slug"] for entry in entries] + [item["slug"] for item in registry.get("module", [])]
    if len(set(slugs)) != len(slugs):
        raise SystemExit("duplicate reference slug in registry")

    outputs: dict[Path, str] = {}
    for entry in entries:
        output = REFERENCE / f"{entry['slug']}.md"
        if entry["name"] == "torchsky":
            outputs[output] = _render_root(entry, manifest, registry)
        else:
            outputs[output] = _render_namespace(entry, manifest, registry)
    for module_entry in registry.get("module", []):
        outputs[REFERENCE / f"{module_entry['slug']}.md"] = _render_module(module_entry, registry)
    outputs[REFERENCE / "index.md"] = _render_index(registry, manifest, entries)
    outputs[REFERENCE / "exceptions.md"] = _render_exceptions(manifest, entries)
    return outputs


def check(outputs: dict[Path, str]) -> int:
    problems: list[str] = []
    for path, content in outputs.items():
        if not path.is_file():
            problems.append(f"missing generated page: {path.relative_to(ROOT)}")
        elif path.read_text(encoding="utf-8") != content:
            problems.append(f"stale generated page: {path.relative_to(ROOT)}")
    expected = {path.name for path in outputs}
    for path in REFERENCE.glob("*.md"):
        if path.name.startswith("_") or path.name in HANDWRITTEN:
            continue
        if path.name not in expected:
            problems.append(f"unexpected page in docs/reference: {path.name}")
    nav_pages = _nav_pages()
    for path in sorted(outputs):
        relative = str(path.relative_to(DOCS))
        if relative not in nav_pages:
            problems.append(f"generated page missing from zensical nav: {relative}")
    for page in nav_pages:
        name = (DOCS / page).name
        if name not in expected and name not in HANDWRITTEN:
            problems.append(f"nav points at unknown reference page: {page}")

    if problems:
        print("Reference pages are out of date:")
        for problem in problems:
            print(f"  - {problem}")
        print("Run `pixi run docs-reference` and re-check.")
        return 1
    print(f"Reference pages are current ({len(outputs)} generated pages).")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="Regenerate reference pages")
    mode.add_argument("--check", action="store_true", help="Fail if pages are stale")
    args = parser.parse_args(argv)

    if str(SRC) not in sys.path:
        sys.path.insert(0, str(SRC))

    outputs = generate()
    if args.check:
        return check(outputs)

    REFERENCE.mkdir(parents=True, exist_ok=True)
    for path, content in outputs.items():
        path.write_text(content, encoding="utf-8")
    stale = [
        path
        for path in REFERENCE.glob("*.md")
        if not path.name.startswith("_")
        and path.name not in HANDWRITTEN
        and path not in outputs
    ]
    for path in stale:
        path.unlink()
    print(f"wrote {len(outputs)} reference pages to {REFERENCE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
