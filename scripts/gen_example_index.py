"""Generate ``docs/examples/index.md``, the curated example gallery.

Examples are grouped by science scenario (``SCENARIOS`` below). Descriptions and
runtimes come from each script's docstring (first line and the sentence
starting ``Runtime``), so the page cannot drift from the code. Every
``examples/*.py`` must be listed in exactly one scenario, which keeps the
gallery curated. Thumbnails live in ``docs/assets/gallery/examples/`` and are
committed; regenerate them deliberately with ``--thumbnails``. Optional sample
output is picked up from ``docs/assets/example-output/<script>.txt``.

    pixi run docs-examples           # regenerate the page
    pixi run docs-examples-check     # fail if the page is stale or incomplete
    pixi run -e test python scripts/gen_example_index.py --thumbnails
"""

