def _docstring(path: Path) -> tuple[str, str]:
    """Return ``(first line, runtime phrase)`` from the module docstring."""
    doc = ast.get_docstring(ast.parse(path.read_text(encoding="utf-8"))) or ""
    flat = " ".join(doc.split())
    first = doc.strip().splitlines()[0].strip() if doc.strip() else path.stem
    match = re.search(r"Runtime ([^.]*(?:\.\d[^.]*)*)\.", flat)
    runtime = match.group(1).strip() if match else ""
    return first.rstrip("."), runtime


def _excerpt(name: str) -> str | None:
    path = OUTPUTS / f"{Path(name).stem}.txt"
    if not path.is_file():
        return None
    lines = [
        line.rstrip()
        for line in path.read_text(encoding="utf-8").splitlines()
        if line.strip()
    ]
    return "\n".join(lines[:12]) if lines else None


def _listed() -> list[str]:
    return [name for _, _, entries in SCENARIOS for name, _ in entries]


def _problems() -> list[str]:
    on_disk = {
        p.stem
        for p in EXAMPLES.glob("*.py")
        if p.name not in EXCLUDE and not p.name.startswith("_")
    }
    listed = _listed()
    problems = [
        f"example not in SCENARIOS: {n}.py" for n in sorted(on_disk - set(listed))
    ]
    problems += [
        f"SCENARIOS lists missing example: {n}.py"
        for n in sorted(set(listed) - on_disk)
    ]
    problems += [
        f"example listed twice: {n}"
        for n in sorted({n for n in listed if listed.count(n) > 1})
    ]
    return problems


def _sample_table() -> list[str]:
    """Sample Data Sources section generated from the example sample registry."""
    sys.path.insert(0, str(EXAMPLES))
    try:
        import _sample_data as sd
    finally:
        sys.path.remove(str(EXAMPLES))
    lines = [
        "## Sample data sources",
        "",
        "Samples are validated (size, magic bytes, sha256 where the server file is",
        "immutable) on every cache hit. Catalogue cones use the TAP services of the Gaia",
        "archive and IRSA, with a `COUNT(*)` check against truncation.",
        "",
        "| Sample | Size | Description | Credit and licence |",
        "|---|---|---|---|",
    ]
    for name, spec in sd.SAMPLES.items():
        size = spec["bytes"]
        size_text = "?" if size is None else f"{size / 1e6:.1f} MB"
        flag = " (opt-in)" if spec["large"] else ""
        desc = " ".join(str(spec["description"]).split())
        lines.append(f"| `{name}`{flag} | {size_text} | {desc} | {spec['license']} |")
    lines.extend(
        [
            "",
            "```bash",
            "pixi run fetch-example-samples                  # all small samples",
            "pixi run fetch-example-samples -- --with-large  # also the opt-in ones",
            "```",
            "",
        ]
    )
    return lines


def render() -> str:
    lines = [
        HEADER,
        "",
        "# Examples",
        "",
        "Curated, runnable scripts that show what torchsky does and how to use it. The",
        "first group works on real public data (Gaia, Planck, SDSS, Chandra, CFHT and more);",
        "each script fetches a small sample once into `~/.cache/torchsky/samples`",
        "(`TORCHSKY_SAMPLE_CACHE` overrides it), is deterministic, uses only public torchsky",
        "APIs, prints a short quantitative result, saves at most one figure to a temporary",
        "directory (or `--out`), and finishes in under a minute on a CPU once its data is",
        "cached. Scripts that take `--device` run on CUDA when it is available. With",
        "`TORCHSKY_EXAMPLE_FAST=1` (set under CI) downloads are forbidden and a script",
        "whose data is not cached exits with status 77, which `pixi run examples` reports",
        "as SKIP. The synthetic examples at the end isolate one mechanism and need no network.",
        "",
        "```bash",
        "pixi run fetch-example-samples            # cache every small sample",
        "pixi run -e test -- python examples/planck_power_spectrum.py --out ./figures",
        "pixi run -e test -- python examples/coadd_dithered_sip.py --device cuda",
        "```",
        "",
        "Scientific campaigns, large real-data runs, and parity scorecards live in",
        "[`torchsky-harness`](https://github.com/astroai/torchsky-harness).",
        "",
    ]
    n_real = len(REAL_SCENARIOS)
    for index, (scenario, intro, entries) in enumerate(SCENARIOS):
        if index == n_real:
            lines.extend(
                [
                    "## Mechanisms with synthetic data",
                    "",
                    "Each example below builds its own inputs to isolate one mechanism.",
                    "",
                ]
            )
        title = scenario if index < n_real else f"{scenario} (synthetic)"
        lines.extend([f"## {title}", "", intro, ""])
        for name, title in entries:
            path = EXAMPLES / f"{name}.py"
            summary, runtime = _docstring(path)
            lines.extend([f"### {title}", ""])
            if (THUMBS / f"{name}.png").is_file():
                lines.extend([f"![{title}](../assets/gallery/examples/{name}.png)", ""])
            text = f"{summary}."
            if runtime:
                text += f" *Runtime: {runtime}.*"
            lines.extend([text, ""])
            lines.extend(
                [
                    f"Script: [`examples/{name}.py`]({GITHUB}/{name}.py)"
                    f" · [site copy](../published-examples/{name}.py)",
                    "",
                ]
            )
            excerpt = _excerpt(name)
            if excerpt:
                lines.extend(["```text", excerpt, "```", ""])
    lines.extend(_sample_table())
    lines.extend(
        [
            "## Applications and evaluation",
            "",
            "- [`examples/applications/catalogue_photoz.py`]"
            "(https://github.com/astroai/torchsky/blob/main/examples/applications/catalogue_photoz.py):"
            " a CLI photometric-redshift pilot that needs an external catalogue and checkpoint;"
            " it is not part of the smoke gate. See [Encoders and ML](../models/encoders.md).",
            "- [Synthetic field fit](https://github.com/astroai/torchsky-harness/blob/main/notebooks/01_field_fit_synthetic.ipynb)",
            "- [Multiband hyperspectral reconstruction](https://github.com/astroai/torchsky-harness/blob/main/notebooks/02_multiband_hyperspectral_synthetic.ipynb)",
            "- [SMACS0723 real-data mini-cutout](https://github.com/astroai/torchsky-harness/blob/main/notebooks/03_smacs0723_real_minicutout.ipynb)",
            "- [SMACS campaign scripts](https://github.com/astroai/torchsky-harness/tree/main/scripts)",
            "",
            "Harness notebooks run from the harness checkout against a separately installed",
            "torchsky build; see its methodology page for subject selection and environment pinning.",
            "",
        ]
    )
    return "\n".join(lines).rstrip() + "\n"


def make_thumbnails(only: list[str] | None = None) -> int:
    """Run each figure-producing example and store a small PNG thumbnail."""
    from PIL import Image

    THUMBS.mkdir(parents=True, exist_ok=True)
    for name in only or _listed():
        script = EXAMPLES / f"{name}.py"
        if '"--out"' not in script.read_text(encoding="utf-8"):
            continue
        with tempfile.TemporaryDirectory(prefix="torchsky-thumb-") as tmp:
            proc = subprocess.run(
                [sys.executable, str(script), "--out", tmp],
                cwd=ROOT,
                capture_output=True,
                text=True,
                check=False,
            )
            if proc.returncode != 0:
                print(f"[skip] {name}: exit {proc.returncode}")
                continue
            figures = sorted(Path(tmp).glob("*.png"))
            preferred = [f for f in figures if f.stem == name or "mollweide" in f.stem]
            if not (preferred or figures):
                continue
            source = (preferred or figures)[0]
            with Image.open(source) as image:
                image = image.convert("RGB")
                if image.width > THUMB_WIDTH:
                    height = round(image.height * THUMB_WIDTH / image.width)
                    image = image.resize(
                        (THUMB_WIDTH, height), Image.Resampling.LANCZOS
                    )
                target = THUMBS / f"{name}.png"
                for colors in (128, 64, 32):
                    image.quantize(colors=colors, dither=Image.Dither.NONE).save(
                        target, optimize=True
                    )
                    if target.stat().st_size < THUMB_MAX_BYTES:
                        break
            print(
                f"[ok] {name}: {target.relative_to(ROOT)} ({target.stat().st_size // 1024} KB)"
            )
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    mode.add_argument(
        "--thumbnails", action="store_true", help="regenerate committed thumbnails"
    )
    parser.add_argument(
        "names", nargs="*", help="with --thumbnails: only these examples (default all)"
    )
    args = parser.parse_args(argv)
    if args.thumbnails:
        return make_thumbnails(args.names or None)
    problems = _problems()
    if problems:
        print("\n".join(problems))
        return 1
    text = render()
    if args.check:
        if not PAGE.is_file() or PAGE.read_text(encoding="utf-8") != text:
            print("docs/examples/index.md is stale; run `pixi run docs-examples`.")
            return 1
        print("Example index is current.")
        return 0
    PAGE.write_text(text, encoding="utf-8")
    print(f"wrote {PAGE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
