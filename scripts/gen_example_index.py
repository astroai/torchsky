#!/usr/bin/env python3
"""Generate ``docs/examples.md`` from the scripts in ``examples/``.

Titles and descriptions come from each script's docstring; demonstrated API
names come from the AST, so the index cannot claim an example uses something it
does not import. Committed sample output (optional) is picked up from
``docs/assets/example-output/<script>.txt``.

    pixi run docs-examples           # regenerate
    pixi run docs-examples-check     # fail if the index is stale
"""

from __future__ import annotations

import argparse
import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EXAMPLES = ROOT / "examples"
DOCS = ROOT / "docs"
PAGE = DOCS / "examples.md"
OUTPUTS = DOCS / "assets" / "example-output"
HEADER = "<!-- Generated by scripts/gen_example_index.py; edit the example docstrings instead. -->"
EXCLUDE = {"test_examples.py", "catalogue_photoz.py"}
DOMAIN_ORDER = [
    "Coordinates and WCS",
    "Sphere and HEALPix",
    "Catalogs",
    "Mapmaking",
    "Fields and models",
    "Observation operators",
    "I/O boundary",
    "Visualization",
]


def _domain(name: str) -> str:
    if "healpix" in name or "sht" in name:
        return "Sphere and HEALPix"
    if "wcs" in name or "astrometr" in name:
        return "Coordinates and WCS"
    if "catalog" in name or "polars" in name:
        return "I/O boundary" if "polar" in name else "Catalogs"
    if "field" in name or "native_" in name:
        return "Fields and models" if "field" in name else "Observation operators"
    if "viz" in name:
        return "Visualization"
    if "table" in name:
        return "I/O boundary"
    if "image" in name or "map" in name:
        return "Mapmaking"
    return "I/O boundary"


def _docstring(path: Path) -> tuple[str, str]:
    module = ast.parse(path.read_text(encoding="utf-8"))
    doc = ast.get_docstring(module) or ""
    lines = [line.strip() for line in doc.splitlines() if line.strip()]
    if not lines:
        return path.stem.replace("_", " ").capitalize(), ""
    title = lines[0].rstrip(".")
    summary = ""
    if len(lines) > 1:
        text = " ".join(lines[1:])
        sentences = text.split(". ")
        summary = ". ".join(sentences[:2]).strip()
        if summary and not summary.endswith("."):
            summary += "."
        if len(summary) > 260:
            summary = summary[:257].rsplit(" ", 1)[0] + "..."
    return title[:1].upper() + title[1:], summary


def _torchsky_imports(path: Path) -> list[str]:
    module = ast.parse(path.read_text(encoding="utf-8"))
    names: set[str] = set()
    for node in ast.walk(module):
        if isinstance(node, ast.ImportFrom) and node.module:
            if node.module.startswith("torchsky"):
                for alias in node.names:
                    if alias.name == "*":
                        continue
                    names.add(f"{node.module}.{alias.name}")
        elif isinstance(node, ast.Import):
            for alias in node.names:
                if alias.name.startswith("torchsky"):
                    names.add(alias.name)
    return sorted(names)


def _excerpt(name: str) -> str | None:
    path = OUTPUTS / f"{Path(name).stem}.txt"
    if not path.is_file():
        return None
    lines = [line.rstrip() for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]
    if not lines:
        return None
    return "\n".join(lines[:12])


def render() -> str:
    rows: dict[str, list[tuple[str, str, str, list[str]]]] = {}
    for path in sorted(EXAMPLES.glob("*.py")):
        if path.name in EXCLUDE or path.name.startswith("_"):
            continue
        title, summary = _docstring(path)
        rows.setdefault(_domain(path.name), []).append(
            (path.name, title, summary, _torchsky_imports(path))
        )
    lines = [
        HEADER,
        "",
        "# Examples",
        "",
        "Standalone scripts that build their own synthetic inputs. Each one is",
        "smoke-run by `pixi run examples`; the demonstrated API names are read from",
        "the script's imports, not hand-maintained.",
        "",
        "Run an example from the repository root:",
        "",
        "```bash",
        "pixi run -e test -- python examples/example_healpix.py",
        "```",
        "",
        "FITS-backed examples use `torchfits` readers and small on-disk fixtures at",
        "the I/O boundary; scientific campaigns and real-data notebooks live in",
        "[`torchsky-harness`](https://github.com/astroai/torchsky-harness).",
        "",
    ]
    order = DOMAIN_ORDER + sorted(set(rows) - set(DOMAIN_ORDER))
    for domain in order:
        entries = rows.get(domain)
        if not entries:
            continue
        lines.extend([f"## {domain}", ""])
        for name, title, summary, apis in entries:
            lines.extend([f"### [`{name}`](published-examples/{name})", ""])
            lines.extend([f"**{title}.** {summary}".strip(), ""])
            if apis:
                formatted = ", ".join(f"`{api.split('.')[-1]}`" for api in apis[:8])
                more = f" (+{len(apis) - 8} more)" if len(apis) > 8 else ""
                lines.extend([f"API: {formatted}{more}", ""])
            excerpt = _excerpt(name)
            if excerpt:
                lines.extend(["Sample output:", "", "```text", excerpt, "```", ""])
        lines.append("")
    lines.extend(
        [
            "## Scientific evaluation examples",
            "",
            "Notebooks and operational scripts are maintained with their evaluation",
            "harness, where dependencies, data policy, scoring, and provenance are",
            "documented together:",
            "",
            "- [Synthetic field fit](https://github.com/astroai/torchsky-harness/blob/main/notebooks/01_field_fit_synthetic.ipynb)",
            "- [Multiband hyperspectral reconstruction](https://github.com/astroai/torchsky-harness/blob/main/notebooks/02_multiband_hyperspectral_synthetic.ipynb)",
            "- [SMACS0723 real-data mini-cutout](https://github.com/astroai/torchsky-harness/blob/main/notebooks/03_smacs0723_real_minicutout.ipynb)",
            "- [SMACS campaign scripts](https://github.com/astroai/torchsky-harness/tree/main/scripts)",
            "- [Hyperspectral fusion onboarding](https://github.com/astroai/torchsky-harness/blob/main/docs/projects/hyperspectral-fusion.md)",
            "- [Calibration evidence workflow](https://github.com/astroai/torchsky-harness/blob/main/docs/calibration-evidence.md)",
            "",
            "Harness notebooks run from the harness checkout against a separately",
            "installed torchsky subject build; see its methodology page for subject",
            "selection and environment pinning.",
            "",
        ]
    )
    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        if not PAGE.is_file() or PAGE.read_text(encoding="utf-8") != text:
            print("docs/examples.md is stale; run `pixi run docs-examples`.")
            return 1
        print("Example index is current.")
        return 0
    PAGE.write_text(text, encoding="utf-8")
    print(f"wrote {PAGE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
