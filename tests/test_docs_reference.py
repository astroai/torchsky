"""The generated reference must cover every public name exactly once.

These checks are structural: they read the committed Markdown, the API
manifest, the registry, and the site navigation. Rendered anchors are verified
after the build by ``scripts/check_reference_anchors.py`` (run in
``pixi run docs-contract``).
"""

from __future__ import annotations

import json
import re
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
REFERENCE = DOCS / "reference"
MANIFEST = DOCS / "api-manifest.json"
REGISTRY = REFERENCE / "_registry.toml"
CONFIG = ROOT / "zensical.toml"
MEMBER = re.compile(r"^        - (\w+)$", re.M)
ANCHOR = re.compile(r'<a id="([^"]+)"></a>')
HEADER = "<!-- Generated by scripts/gen_reference.py"


def _registry() -> dict:
    return tomllib.loads(REGISTRY.read_text(encoding="utf-8"))


def _manifest() -> dict[str, list[str]]:
    return json.loads(MANIFEST.read_text(encoding="utf-8"))


def _nav_pages() -> list[str]:
    config = tomllib.loads(CONFIG.read_text(encoding="utf-8"))

    def walk(node: object) -> list[str]:
        pages: list[str] = []
        if isinstance(node, list):
            for item in node:
                pages.extend(walk(item))
        elif isinstance(node, dict):
            for value in node.values():
                pages.extend(walk(value))
        elif isinstance(node, str):
            pages.append(node)
        return pages

    return walk(config["project"].get("nav", []))


def test_registry_matches_the_public_manifest() -> None:
    registry = _registry()
    manifest = _manifest()
    namespaces = [entry["name"] for entry in registry["namespace"]]
    assert sorted(namespaces) == sorted(manifest)
    slugs = [entry["slug"] for entry in registry["namespace"]]
    slugs += [entry["slug"] for entry in registry.get("module", [])]
    assert len(slugs) == len(set(slugs))


def test_every_public_name_has_exactly_one_reference_entry() -> None:
    manifest = _manifest()
    registry = _registry()
    pages = {
        entry["name"]: REFERENCE / f"{entry['slug']}.md"
        for entry in registry["namespace"]
    }
    module_pages = {
        entry["name"]: REFERENCE / f"{entry['slug']}.md"
        for entry in registry.get("module", [])
    }
    covered: dict[str, int] = {}
    for namespace, names in manifest.items():
        page = pages[namespace]
        assert page.is_file(), f"missing reference page for {namespace}"
        text = page.read_text(encoding="utf-8")
        assert HEADER in text, f"{page.name} is not generated"
        entries = set(MEMBER.findall(text))
        for anchor in ANCHOR.findall(text):
            entries.add(anchor.removeprefix(namespace + "."))
        for name in names:
            if namespace == "torchsky" and f"torchsky.{name}" in pages:
                full = f"torchsky.{name}"
            elif f"{namespace}.{name}" in module_pages:
                full = f"{namespace}.{name}"
            else:
                full = f"{namespace}.{name}"
                assert name in entries, f"{full} is missing from {page.name}"
            covered[full] = covered.get(full, 0) + 1
    duplicates = sorted(name for name, count in covered.items() if count > 1)
    assert not duplicates, f"names documented more than once: {duplicates}"


def test_every_generated_page_is_in_the_navigation() -> None:
    registry = _registry()
    nav = set(_nav_pages())
    expected = [
        f"reference/{entry['slug']}.md"
        for entry in registry["namespace"] + registry.get("module", [])
    ]
    expected += ["reference/index.md", "reference/exceptions.md"]
    missing = sorted(page for page in expected if page not in nav)
    assert not missing, f"reference pages missing from nav: {missing}"
    handwritten = {path.name for path in REFERENCE.glob("*.md") if HEADER not in path.read_text(encoding="utf-8")}
    assert handwritten == {"runtime-contract.md"}, f"unexpected handwritten reference pages: {handwritten}"
